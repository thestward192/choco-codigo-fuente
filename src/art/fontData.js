// Marcas diacríticas (se centran sobre la letra base).
const MARKS = {
  acute: ['.#', '#.'],
  diaeresis: ['#.#'],
  tilde: ['.#.#', '#.#.'],
};

function withMark(base, mark, upper) {
  const m = MARKS[mark];
  const mw = Math.max(...m.map((r) => r.length));
  const w = Math.max(base.w, mw);
  const bx = Math.floor((w - base.w) / 2);
  const mx = Math.round((w - mw) / 2);
  // Filas: para mayúsculas las marcas van en −3..−2 (top = −3); minúsculas en 0..1.
  const markTop = upper ? (mark === 'diaeresis' ? -2 : -3) : 0;
  const top = Math.min(0, markTop);
  const height = Math.max(base.rows.length - top, markTop - top + m.length);
  const grid = Array.from({ length: height }, () => '.'.repeat(w).split(''));
  base.rows.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) if (r[x] === '#') grid[y - top][x + bx] = '#';
  });
  m.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) if (r[x] === '#') grid[markTop - top + y][Math.min(w - 1, x + mx)] = '#';
  });
  return { rows: grid.map((r) => r.join('')), w, top };
}

const ACCENTED = {
  á: ['a', 'acute'],
  é: ['e', 'acute'],
  í: ['ı', 'acute'],
  ó: ['o', 'acute'],
  ú: ['u', 'acute'],
  ü: ['u', 'diaeresis'],
  ñ: ['n', 'tilde'],
  Á: ['A', 'acute'],
  É: ['E', 'acute'],
  Í: ['I', 'acute'],
  Ó: ['O', 'acute'],
  Ú: ['U', 'acute'],
  Ü: ['U', 'diaeresis'],
  Ñ: ['N', 'tilde'],
};

export const GLYPHS = { ...BASE };
for (const [ch, [base, mark]] of Object.entries(ACCENTED)) {
  GLYPHS[ch] = withMark(BASE[base], mark, base === base.toUpperCase() && base !== 'ı');
}

// Variante "negrita" para títulos: engrosa cada glifo 1 px a la derecha.
export function boldGlyph(g) {
  const rows = g.rows.map((r) => {
    const out = (r + '.').split('');
    for (let x = 0; x < r.length; x++) if (r[x] === '#') out[x + 1] = '#';
    return out.join('');
  });
  return { rows, w: g.w + 1, top: g.top };
}

export const FONT_METRICS = {
  lineHeight: 11,
  spacing: 1, // píxeles entre letras
  capHeight: 7,
};

// Ancho en píxeles de un texto (una línea).
export function measureText(text, bold = false) {
  let w = 0;
  let count = 0;
  for (const ch of text) {
    const g = GLYPHS[ch] || GLYPHS['?'];
    w += g.w + (bold ? 1 : 0);
    count++;
  }
  return count > 0 ? w + (count - 1) * FONT_METRICS.spacing : 0;
}

// Parte un texto en líneas que caben en `maxWidth`.
export function wrapText(text, maxWidth, bold = false) {
  const lines = [];
  for (const para of text.split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const word of words) {
      const test = line ? `${line} ${word}` : word;
      if (measureText(test, bold) <= maxWidth || !line) line = test;
      else {
        lines.push(line);
        line = word;
      }
    }
    lines.push(line);
  }
  return lines;
}
